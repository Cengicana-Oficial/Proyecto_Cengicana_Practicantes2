const fs = require('fs');
const path = require('path');
const vm = require('vm');
const assert = require('assert');
const babel = require('@babel/core');
let checks = 0;
const ok = (condition, message) => { assert(condition, message); checks++; };
function cargar(archivo, deps = {}) {
  const source = fs.readFileSync(archivo, 'utf8');
  const code = babel.transformSync(source, { configFile: false, babelrc: false, plugins: ['@babel/plugin-transform-modules-commonjs'] }).code;
  const exports = {};
  vm.runInNewContext(code, { exports, require: (id) => deps[id] || require(id), console, URL, window: { location: { origin: 'http://localhost:8085' } } }, { filename: archivo });
  return exports;
}
const stats = cargar('resources/js/estadistica.js');
const reporte = cargar('resources/js/views/soporte/reportes/reporte-estadistica.js', { '../../../estadistica': stats });
const parcelas = [1,2,3,4].map((id) => ({id, tratamiento: id < 3 ? 'T1' : 'T2', repeticion: id % 2 ? 1 : 2}));
const variable = {id:1, nombre:'Altura', tipo:'Numerica'};
const registros = [];
[10,14,20,24].forEach((valor, i) => registros.push({variable_id:1, parcela_id:i+1, fecha:'2026-10-01', valor}));
registros.push({variable_id:1, parcela_id:1, fecha:'2026-10-02', valor:14});
[0,16,22].forEach((valor, i) => registros.push({variable_id:1, parcela_id:i+1, fecha:'2026-11-01', valor}));
registros.push({variable_id:1, parcela_id:1, fecha:'2026-10-01', valor:''}, {variable_id:1, parcela_id:2, fecha:'2026-10-01', valor:'Infinity'}, {variable_id:2, parcela_id:1, fecha:'2026-10-01', valor:999});
const analisis = reporte.analizarVariable(variable, registros, parcelas, {usa_bloques:true}, 7, .05);
ok(analisis.muestreos.length === 2, 'Agrupación de fechas en muestreos.');
ok(analisis.muestreos[0].obs.length === 4, 'Una observación por parcela.');
ok(analisis.muestreos[0].obs.find((r) => r.parcela === 1).valor === 12, 'Promedia lecturas repetidas de una parcela.');
ok(analisis.muestreos[0].res.diseno === 'DBCA', 'Diseño en bloques completos.');
const esperado = stats.anova([{trat:'T1',bloque:1,valor:12},{trat:'T1',bloque:2,valor:14},{trat:'T2',bloque:1,valor:20},{trat:'T2',bloque:2,valor:24}],{bloques:true,alfa:.05});
ok(analisis.muestreos[0].res.p === esperado.p && analisis.muestreos[0].res.tukey.q === esperado.tukey.q, 'Mismo motor y resultados de ANOVA/Tukey de Evaluaciones.');
ok(analisis.muestreos[1].res.diseno === 'DCA' && !!analisis.muestreos[1].res.aviso, 'Advertencia cuando faltan bloques.');
ok(analisis.auc.excluidas === 1 && analisis.auc.res.N === 3, 'Área bajo la curva solo con parcelas completas.');
ok(analisis.puntos === 8 && analisis.muestreos[1].obs[0].valor === 0, 'Conserva cero y omite vacíos, infinitos y otras variables.');
ok(reporte.analizarVariable(variable, registros, parcelas, {usa_bloques:false}, 0, .01).muestreos.length === 3, 'Fechas independientes y significancia configurable.');
const vacio = reporte.analizarVariable({id:99}, registros, parcelas, {}, 7, .05);
ok(vacio.muestreos.length === 0 && vacio.auc === null, 'Variable sin datos.');
const vue = require('vue-template-compiler');
const archivo = 'resources/js/views/soporte/reportes/index.vue';
const componente = vue.parseComponent(fs.readFileSync(archivo,'utf8'));
assert.deepStrictEqual(vue.compile(componente.template.content).errors, []); checks++;
const temporal = path.join('tests','.reportes-componente.tmp.js'); fs.writeFileSync(temporal, componente.script.content);
const dashboard = cargar(temporal).default; fs.unlinkSync(temporal);
const ctx = {programa:1,proyecto:10,ensayoId:'',ensayos:[{id:1,programa_id:1,proyecto_id:10},{id:2,programa_id:1,proyecto_id:11},{id:3,programa_id:2,proyecto_id:20}]};
ctx.ensayosDisponibles = dashboard.computed.ensayosDisponibles.call(ctx);
ok(ctx.ensayosDisponibles.length === 1 && dashboard.computed.seleccion.call(ctx)[0].id === 1, 'Filtros acumulativos de programa y proyecto.');
const enlace = dashboard.methods.informeUrl.call({baseUrl:'http://localhost:8085/sigec/soporte/reportes',desde:'2026-11-01',hasta:'2026-11-02'},1);
ok(enlace.includes('/sigec/soporte/reportes/informe/1') && enlace.includes('desde=2026-11-01'), 'Informe conserva prefijo y periodo.');
ok(dashboard.computed.errorFechas.call({desde:'2026-11-02',hasta:'2026-11-01'}), 'Detecta periodos invertidos.');
console.log(`OK: ${checks} comprobaciones de estadística y filtros de reportes.`);
