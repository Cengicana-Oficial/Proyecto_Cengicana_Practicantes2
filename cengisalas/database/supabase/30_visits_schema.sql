-- CengiSalas / Supabase
-- 30: esquema PostgreSQL del modulo de Visitas.
-- Conserva nombres de tablas y columnas para no alterar las vistas PHP existentes.

begin;

create schema if not exists visits;
revoke all on schema visits from public,anon,authenticated;

create table if not exists visits.aprobadores (
  id_aprobador integer generated by default as identity primary key,
  profile_id uuid unique references public.profiles(id) on delete set null,
  nombre varchar(100) not null,
  apellido varchar(100),
  estado smallint default 1 check (estado in (0,1))
);

create table if not exists visits.areas_interes (
  id_area integer generated by default as identity primary key,
  nombre_area varchar(100) not null,
  profesional_area varchar(150) not null default '',
  estado smallint default 1 check (estado in (0,1)),
  correo_area varchar(150) not null
);

create table if not exists visits.estado_pago (
  id_estado_pago integer generated by default as identity primary key,
  nombre_estado_pago varchar(50) not null unique
);

create table if not exists visits.estados (
  id_estado integer generated by default as identity primary key,
  nombre_estado varchar(50) not null unique
);

create table if not exists visits.niveles_academicos (
  id_nivel integer generated by default as identity primary key,
  nombre_nivel varchar(100) not null unique,
  estado smallint default 1 check (estado in (0,1))
);

create table if not exists visits.solicitantes (
  id_solicitante integer generated by default as identity primary key,
  nombre_solicitante varchar(150) not null,
  nombre_institucion varchar(150) not null,
  correo varchar(100) not null,
  telefono varchar(20),
  estado smallint default 1 check (estado in (0,1))
);

create table if not exists visits.solicitudes (
  id_solicitud integer generated by default as identity primary key,
  id_solicitante integer not null references visits.solicitantes(id_solicitante) on delete restrict,
  tipo_visita varchar(20) not null default 'cengicana' check (tipo_visita in ('cengicana','museo_azucar')),
  fecha_visita date not null,
  hora_visita time not null,
  cantidad_visitantes integer not null check (cantidad_visitantes > 0),
  id_nivel integer not null references visits.niveles_academicos(id_nivel) on delete restrict,
  ruta_carta_pdf varchar(500) not null default '',
  nombre_archivo_pdf varchar(255) not null default '',
  fecha_subida_pdf timestamptz default now(),
  id_estado integer not null references visits.estados(id_estado) on delete restrict,
  fecha_registro timestamptz default now(),
  correo_enviado smallint not null default 0 check (correo_enviado in (0,1)),
  fecha_envio_correo timestamptz
);

create index if not exists ix_visits_requests_date on visits.solicitudes(fecha_visita,hora_visita);
create index if not exists ix_visits_requests_status on visits.solicitudes(id_estado,fecha_registro desc);

create table if not exists visits.solicitud_areas (
  id integer generated by default as identity primary key,
  id_solicitud integer not null references visits.solicitudes(id_solicitud) on delete cascade,
  id_area integer not null references visits.areas_interes(id_area) on delete restrict,
  id_area_asignada integer references visits.areas_interes(id_area) on delete restrict,
  unique (id_solicitud,id_area)
);

create table if not exists visits.solicitud_museo (
  id_museo integer generated by default as identity primary key,
  id_solicitud integer not null unique references visits.solicitudes(id_solicitud) on delete cascade,
  cant_extranjeros integer not null default 0 check (cant_extranjeros >= 0),
  precio_extranjero numeric(10,2) not null default 80.00,
  cant_adultos integer not null default 0 check (cant_adultos >= 0),
  precio_adulto numeric(10,2) not null default 25.00,
  cant_adultos_mayores integer not null default 0 check (cant_adultos_mayores >= 0),
  precio_adulto_mayor numeric(10,2) not null default 15.00,
  cant_estudiantes integer not null default 0 check (cant_estudiantes >= 0),
  precio_estudiante numeric(10,2) not null default 15.00,
  cant_ninos integer not null default 0 check (cant_ninos >= 0),
  precio_nino numeric(10,2) not null default 15.00,
  total numeric(10,2) not null default 0.00,
  id_estado_pago integer not null default 1 references visits.estado_pago(id_estado_pago) on delete restrict,
  forma_pago varchar(20) not null check (forma_pago in ('transferencia','debito','credito')),
  moneda varchar(3) not null check (moneda in ('GTQ','USD')),
  nombre_factura varchar(200) not null,
  nit varchar(50) not null,
  direccion varchar(300) not null,
  ruta_carta_pdf varchar(500),
  nombre_archivo_pdf varchar(200),
  fecha_subida_pdf timestamptz,
  fecha_registro timestamptz not null default now()
);

create table if not exists visits.aprobacion_solicitud (
  id_aprobacion integer generated by default as identity primary key,
  id_solicitud integer not null references visits.solicitudes(id_solicitud) on delete cascade,
  id_aprobador integer not null references visits.aprobadores(id_aprobador) on delete restrict,
  id_estado integer not null references visits.estados(id_estado) on delete restrict,
  comentario text,
  fecha_aprobacion timestamptz default now()
);

create index if not exists ix_visits_approval_request on visits.aprobacion_solicitud(id_solicitud,fecha_aprobacion desc);

create table if not exists visits.solicitudes_ocultas (
  id_oculta integer generated by default as identity primary key,
  id_solicitud integer not null unique references visits.solicitudes(id_solicitud) on delete cascade,
  fecha_ocultamiento timestamptz not null default now()
);

create table if not exists visits.solicitud_reservas_cengisalas (
  id integer generated by default as identity primary key,
  id_solicitud integer not null unique references visits.solicitudes(id_solicitud) on delete cascade,
  request_code varchar(30) not null,
  space_id bigint not null references public.spaces(id) on delete restrict,
  space_name varchar(160) not null,
  configuration_id bigint not null references public.configuration_types(id) on delete restrict,
  configuration_name varchar(120) not null,
  hora_fin time not null,
  created_by varchar(191),
  created_by_profile_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists visits.migration_runs (
  id bigint generated always as identity primary key,
  source_name text not null,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  status text not null default 'running' check (status in ('running','completed','failed')),
  row_counts jsonb not null default '{}'::jsonb,
  error_message text
);

-- Documentos privados. La ruta guardada en las tablas anteriores sera la ruta
-- del objeto dentro de este bucket despues de ejecutar la migracion.
insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values(
  'visit-documents','visit-documents',false,10485760,
  array[
    'application/pdf',
    'image/jpeg',
    'image/png',
    'image/webp',
    'application/msword',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    'application/vnd.ms-excel',
    'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
  ]
)
on conflict (id) do update set public=false,file_size_limit=excluded.file_size_limit,
  allowed_mime_types=excluded.allowed_mime_types;

alter table visits.aprobadores enable row level security;
alter table visits.areas_interes enable row level security;
alter table visits.estado_pago enable row level security;
alter table visits.estados enable row level security;
alter table visits.niveles_academicos enable row level security;
alter table visits.solicitantes enable row level security;
alter table visits.solicitudes enable row level security;
alter table visits.solicitud_areas enable row level security;
alter table visits.solicitud_museo enable row level security;
alter table visits.aprobacion_solicitud enable row level security;
alter table visits.solicitudes_ocultas enable row level security;
alter table visits.solicitud_reservas_cengisalas enable row level security;
alter table visits.migration_runs enable row level security;

revoke all on all tables in schema visits from anon,authenticated;
revoke all on all sequences in schema visits from anon,authenticated;

-- El navegador nunca escribe directamente en el bucket. Los archivos se sirven
-- mediante el backend autenticado del modulo o una URL firmada de corta duracion.
drop policy if exists visit_documents_authenticated_read on storage.objects;
create policy visit_documents_authenticated_read on storage.objects for select to authenticated
using (bucket_id='visit-documents' and private.has_module_access('visitas'));

commit;
