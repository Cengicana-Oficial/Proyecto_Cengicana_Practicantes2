-- Flujo completo del panel de gestion de visitas (Supabase / PostgreSQL).

insert into visits.estados (nombre_estado)
select 'ORGANIZANDO'
where not exists (select 1 from visits.estados where upper(trim(nombre_estado)) = 'ORGANIZANDO');

insert into visits.estados (nombre_estado)
select 'REVISION_DIRECTOR'
where not exists (select 1 from visits.estados where upper(trim(nombre_estado)) = 'REVISION_DIRECTOR');

insert into visits.estados (nombre_estado)
select 'NOTIFICADO'
where not exists (select 1 from visits.estados where upper(trim(nombre_estado)) = 'NOTIFICADO');

create table if not exists visits.solicitud_gestion_visita (
    id_solicitud integer primary key references visits.solicitudes(id_solicitud) on delete cascade,
    agenda_nombre text,
    agenda_ruta text,
    notif_areas_at timestamptz,
    notif_institucion_at timestamptz,
    contacto_guardado_at timestamptz,
    updated_at timestamptz not null default now()
);

create table if not exists visits.solicitud_fotos_visita (
    id_foto bigint generated by default as identity primary key,
    id_solicitud integer not null references visits.solicitudes(id_solicitud) on delete cascade,
    nombre_archivo text not null,
    ruta_archivo text not null,
    created_at timestamptz not null default now()
);

create index if not exists idx_fotos_visita_solicitud
    on visits.solicitud_fotos_visita(id_solicitud);

create table if not exists visits.solicitud_eventos_visita (
    id_evento bigint generated by default as identity primary key,
    id_solicitud integer not null references visits.solicitudes(id_solicitud) on delete cascade,
    tipo text not null,
    descripcion text not null,
    actor text,
    created_at timestamptz not null default now()
);

create index if not exists idx_eventos_visita_solicitud
    on visits.solicitud_eventos_visita(id_solicitud, created_at);

revoke all on visits.solicitud_gestion_visita from anon, authenticated;
revoke all on visits.solicitud_fotos_visita from anon, authenticated;
revoke all on visits.solicitud_eventos_visita from anon, authenticated;

-- Las agendas aceptan PDF, Word y Excel; las fotografías pueden ser JPG,
-- PNG o WEBP. Se actualiza el bucket también en instalaciones existentes.
update storage.buckets
set allowed_mime_types = array[
  'application/pdf',
  'image/jpeg',
  'image/png',
  'image/webp',
  'application/msword',
  'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  'application/vnd.ms-excel',
  'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
]
where id = 'visit-documents';
