-- SalaFlow / Supabase
-- 02: tablas, restricciones, índices y disparadores generales.

begin;
set search_path = public, extensions;

create table if not exists public.organizations (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  can_request_refreshments boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.departments (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations(id) on delete restrict,
  name text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (organization_id, name),
  unique (id, organization_id)
);

-- auth.users conserva credenciales; profiles solo contiene datos de la aplicación.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  organization_id bigint references public.organizations(id) on delete restrict,
  department_id bigint references public.departments(id) on delete restrict,
  full_name text not null,
  role public.app_role not null default 'user',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'profiles_department_organization_fk') then
    alter table public.profiles
      add constraint profiles_department_organization_fk
      foreign key (department_id, organization_id)
      references public.departments(id, organization_id) on delete restrict;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'profiles_department_requires_organization') then
    alter table public.profiles
      add constraint profiles_department_requires_organization
      check (department_id is null or organization_id is not null);
  end if;
end $$;

create table if not exists public.meeting_types (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  is_active boolean not null default true
);

create table if not exists public.configuration_types (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  description text,
  image_path text,
  is_active boolean not null default true
);

create table if not exists public.refreshments (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  is_active boolean not null default true
);

-- Un room es un salón físico. El bloqueo por conflicto siempre se realiza aquí.
create table if not exists public.rooms (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  location text,
  description text,
  hourly_consumption_kwh numeric(10,2) not null default 0 check (hourly_consumption_kwh >= 0),
  allows_usage_cost boolean not null default false,
  cost_one_hour numeric(12,2) check (cost_one_hour is null or cost_one_hour >= 0),
  cost_four_to_eight_hours numeric(12,2) check (cost_four_to_eight_hours is null or cost_four_to_eight_hours >= 0),
  cost_extra_hour_after_eight numeric(12,2) check (cost_extra_hour_after_eight is null or cost_extra_hour_after_eight >= 0),
  is_active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint rooms_usage_cost_scope check (
    code in ('ROOM_1','ROOM_2','ROOM_3')
    or (
      not allows_usage_cost
      and cost_one_hour is null
      and cost_four_to_eight_hours is null
      and cost_extra_hour_after_eight is null
    )
  )
);

-- Un space es una opción reservable. SPACE_1_2 agrupa físicamente los salones 1 y 2.
create table if not exists public.spaces (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  space_type public.space_type not null default 'single',
  is_active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.space_rooms (
  space_id bigint not null references public.spaces(id) on delete cascade,
  room_id bigint not null references public.rooms(id) on delete restrict,
  primary key (space_id, room_id)
);
create index if not exists ix_space_rooms_room on public.space_rooms(room_id, space_id);

create table if not exists public.space_capacities (
  space_id bigint not null references public.spaces(id) on delete cascade,
  configuration_type_id bigint not null references public.configuration_types(id) on delete restrict,
  capacity integer not null check (capacity > 0),
  primary key (space_id, configuration_type_id)
);

-- Contiene los datos comunes de una solicitud simple o de una serie recurrente.
create table if not exists public.meetings (
  id uuid primary key default gen_random_uuid(),
  request_code text not null unique,
  requested_by uuid references auth.users(id) on delete set null,
  requester_name text not null,
  requester_email text,
  contact_name text,
  contact_email text,
  contact_phone text,
  request_source text not null default 'registered' check (request_source in ('registered','public','paid')),
  paid_offering_code text,
  quoted_amount numeric(12,2) check (quoted_amount is null or quoted_amount >= 0),
  payment_status text not null default 'pending' check (payment_status in ('pending','quoted','paid','cancelled')),
  request_organization_id bigint not null references public.organizations(id) on delete restrict,
  request_department_id bigint references public.departments(id) on delete restrict,
  meeting_type_id bigint not null references public.meeting_types(id) on delete restrict,
  configuration_type_id bigint not null references public.configuration_types(id) on delete restrict,
  title text not null check (length(btrim(title)) between 3 and 180),
  description text,
  observations text constraint meetings_observations_length check (observations is null or length(observations) <= 1000),
  attendees integer not null check (attendees > 0),
  recurrence_type public.recurrence_type not null default 'none',
  recurrence_interval integer not null default 1 check (recurrence_interval > 0),
  recurrence_end_date date,
  timezone text not null default 'America/Guatemala',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists ix_meetings_requester_created on public.meetings(requested_by, created_at desc);

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'meetings_department_organization_fk') then
    alter table public.meetings
      add constraint meetings_department_organization_fk
      foreign key (request_department_id, request_organization_id)
      references public.departments(id, organization_id) on delete restrict;
  end if;
end $$;

create table if not exists public.meeting_refreshments (
  meeting_id uuid not null references public.meetings(id) on delete cascade,
  refreshment_id bigint not null references public.refreshments(id) on delete restrict,
  quantity integer check (quantity is null or quantity > 0),
  notes text,
  primary key (meeting_id, refreshment_id)
);

-- Cada fecha de una recurrencia es independiente para poder moverla, aprobarla o cancelarla.
create table if not exists public.meeting_occurrences (
  id uuid primary key default gen_random_uuid(),
  meeting_id uuid not null references public.meetings(id) on delete cascade,
  space_id bigint not null references public.spaces(id) on delete restrict,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  status public.meeting_status not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_at > starts_at),
  unique (meeting_id, starts_at)
);
create index if not exists ix_occurrences_daily_status on public.meeting_occurrences(starts_at, status);
create index if not exists ix_occurrences_space_time on public.meeting_occurrences(space_id, starts_at, ends_at, status);

-- Historial inmutable de estados; conserva motivo, responsable y fecha/hora.
create table if not exists public.meeting_occurrence_status_history (
  id bigint generated always as identity primary key,
  occurrence_id uuid not null references public.meeting_occurrences(id) on delete cascade,
  from_status public.meeting_status,
  to_status public.meeting_status not null,
  reason text,
  changed_by uuid references auth.users(id) on delete set null,
  actor_name text not null,
  actor_role public.app_role not null,
  changed_at timestamptz not null default now()
);
create index if not exists ix_status_history_occurrence_date on public.meeting_occurrence_status_history(occurrence_id, changed_at desc);
create index if not exists ix_status_history_status_date on public.meeting_occurrence_status_history(to_status, changed_at desc);

create table if not exists public.meeting_occurrence_space_history (
  id bigint generated always as identity primary key,
  occurrence_id uuid not null references public.meeting_occurrences(id) on delete cascade,
  old_space_id bigint references public.spaces(id) on delete restrict,
  new_space_id bigint not null references public.spaces(id) on delete restrict,
  changed_by uuid references auth.users(id) on delete set null,
  actor_name text not null,
  actor_role public.app_role not null,
  reason text,
  changed_at timestamptz not null default now()
);
create index if not exists ix_space_history_occurrence_date on public.meeting_occurrence_space_history(occurrence_id, changed_at desc);

create table if not exists public.maintenance_events (
  id uuid primary key default gen_random_uuid(),
  room_id bigint not null references public.rooms(id) on delete restrict,
  title text not null default 'Mantenimiento',
  reason text not null,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  all_day boolean not null default false,
  status public.maintenance_status not null default 'scheduled',
  created_by uuid references auth.users(id) on delete set null,
  cancelled_by uuid references auth.users(id) on delete set null,
  cancelled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_at > starts_at)
);
create index if not exists ix_maintenance_room_time on public.maintenance_events(room_id, starts_at, ends_at, status);

-- Fuente única de conflictos. Una reunión combinada crea un bloqueo para room 1 y otro para room 2.
create table if not exists public.room_blocks (
  id bigint generated always as identity primary key,
  room_id bigint not null references public.rooms(id) on delete restrict,
  occurrence_id uuid references public.meeting_occurrences(id) on delete cascade,
  maintenance_id uuid references public.maintenance_events(id) on delete cascade,
  block_type public.room_block_type not null,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  during tstzrange generated always as (tstzrange(starts_at, ends_at, '[)')) stored,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  check (ends_at > starts_at),
  check (
    (block_type in ('meeting','payment_hold') and occurrence_id is not null and maintenance_id is null)
    or
    (block_type = 'maintenance' and maintenance_id is not null and occurrence_id is null)
  )
);
create index if not exists ix_room_blocks_occurrence on public.room_blocks(occurrence_id) where occurrence_id is not null;
create index if not exists ix_room_blocks_maintenance on public.room_blocks(maintenance_id) where maintenance_id is not null;

-- La exclusión GiST evita solapamientos incluso si dos administradores aprueban al mismo tiempo.
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'room_blocks_no_overlap'
      and conrelid = 'public.room_blocks'::regclass
  ) then
    alter table public.room_blocks
      add constraint room_blocks_no_overlap
      exclude using gist (room_id with =, during with &&)
      where (active);
  end if;
end $$;

create table if not exists public.audit_log (
  id bigint generated always as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  actor_role public.app_role,
  action text not null,
  entity_type text not null,
  entity_id text not null,
  old_data jsonb,
  new_data jsonb,
  created_at timestamptz not null default now()
);
create index if not exists ix_audit_entity on public.audit_log(entity_type, entity_id, created_at desc);

-- Canal mínimo para que el tablero reciba un evento y vuelva a cargar el estado público.
create table if not exists public.board_events (
  id bigint generated always as identity primary key,
  event_type text not null,
  entity_type text not null,
  entity_id text not null,
  created_at timestamptz not null default now()
);

create or replace function private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

do $$
declare t text;
begin
  foreach t in array array['organizations','profiles','rooms','spaces','meetings','meeting_occurrences','maintenance_events']
  loop
    execute format('drop trigger if exists set_updated_at on public.%I', t);
    execute format('create trigger set_updated_at before update on public.%I for each row execute function private.set_updated_at()', t);
  end loop;
end $$;

revoke all on function private.set_updated_at() from public;

commit;
