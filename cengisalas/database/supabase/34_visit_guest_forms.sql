-- 34: formulario público para registrar los visitantes de una solicitud aprobada.
begin;

create table if not exists visits.solicitud_formularios_visitantes (
  id_formulario bigint generated by default as identity primary key,
  id_solicitud integer not null unique references visits.solicitudes(id_solicitud) on delete cascade,
  token_hash varchar(64) not null unique,
  token_hint varchar(12) not null default '',
  fecha_creacion timestamptz not null default now(),
  fecha_envio timestamptz,
  fecha_expiracion timestamptz,
  fecha_completado timestamptz,
  listado_ruta varchar(500),
  listado_nombre varchar(255)
);

create index if not exists ix_visits_guest_forms_token
  on visits.solicitud_formularios_visitantes(token_hash);

create table if not exists visits.solicitud_visitantes (
  id_visitante bigint generated by default as identity primary key,
  id_solicitud integer not null references visits.solicitudes(id_solicitud) on delete cascade,
  nombre_completo varchar(180) not null,
  orden integer not null default 1,
  fecha_registro timestamptz not null default now(),
  unique (id_solicitud, orden)
);

create index if not exists ix_visits_guest_names_request
  on visits.solicitud_visitantes(id_solicitud, orden);

alter table visits.solicitud_formularios_visitantes enable row level security;
alter table visits.solicitud_visitantes enable row level security;
revoke all on visits.solicitud_formularios_visitantes from anon, authenticated;
revoke all on visits.solicitud_visitantes from anon, authenticated;
revoke all on sequence visits.solicitud_formularios_visitantes_id_formulario_seq from anon, authenticated;
revoke all on sequence visits.solicitud_visitantes_id_visitante_seq from anon, authenticated;

commit;
