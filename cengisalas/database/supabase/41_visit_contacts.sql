-- CengiSalas / Visitas: contactos agregados manualmente.
--   interno: personas de Cengicaña asociadas a un área; pueden recibir las
--            notificaciones de visitas además del responsable del área.
--   externo: solicitantes o instituciones del directorio, aunque todavía no
--            hayan enviado una solicitud. Si el correo coincide con el de una
--            solicitud, estos datos se usan como versión corregida del contacto.
-- Los contactos no se borran físicamente: se desactivan (estado = 0).

begin;

create table if not exists visits.contactos_visita (
  id_contacto integer generated by default as identity primary key,
  tipo varchar(10) not null check (tipo in ('interno','externo')),
  nombre varchar(150) not null check (length(trim(nombre)) >= 2),
  correo varchar(150),
  telefono varchar(30),
  institucion varchar(200),
  cargo varchar(120),
  id_area integer references visits.areas_interes(id_area) on delete set null,
  recibe_notificaciones smallint not null default 1 check (recibe_notificaciones in (0,1)),
  notas varchar(500),
  estado smallint not null default 1 check (estado in (0,1)),
  creado_por varchar(150),
  creado_en timestamptz not null default now(),
  actualizado_por varchar(150),
  actualizado_en timestamptz,
  check (correo is not null or telefono is not null),
  check (tipo = 'externo' or id_area is not null)
);

-- Un mismo correo activo solo puede registrarse una vez por área (internos)
-- o una vez en el directorio (externos).
create unique index if not exists ux_contactos_visita_correo
  on visits.contactos_visita (tipo, lower(correo), coalesce(id_area, 0))
  where estado = 1 and correo is not null;

create index if not exists ix_contactos_visita_tipo_estado
  on visits.contactos_visita (tipo, estado);

alter table visits.contactos_visita enable row level security;
revoke all on visits.contactos_visita from anon, authenticated;

commit;
