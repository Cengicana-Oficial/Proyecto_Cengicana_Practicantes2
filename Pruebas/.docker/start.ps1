param([switch]$PrepareOnly)
$ErrorActionPreference = 'Stop'
$projectRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\..'))
$baseCompose = Join-Path $projectRoot 'docker-compose.prod.yml'
$overrideCompose = Join-Path $PSScriptRoot 'compose.yml'

# Read the current base configuration so mounts added by other modules survive.
# Do not write or print environment variables from the resolved configuration.
$rawConfig = & docker compose -f $baseCompose config --format json
if ($LASTEXITCODE -ne 0) { throw 'No se pudo leer la configuración Docker principal.' }
$config = ($rawConfig -join "`n") | ConvertFrom-Json
$mounts = @($config.services.app.volumes | Where-Object {
    $_.target -ne '/var/www/html/Pruebas' -and
    -not $_.target.StartsWith('/var/www/html/Pruebas/') -and
    $_.target -ne '/var/lib/servicios-tecnicos'
})
$modulePath = Join-Path $projectRoot 'Pruebas'
$privatePath = Join-Path $PSScriptRoot 'private'
if (-not (Test-Path -LiteralPath (Join-Path $modulePath 'index.php') -PathType Leaf)) {
    throw 'No existe el index.php de Servicios Técnicos.'
}
New-Item -ItemType Directory -Path $privatePath -Force | Out-Null
$mounts += [pscustomobject]@{type='bind'; source=$modulePath; target='/var/www/html/Pruebas'}
$mounts += [pscustomobject]@{type='bind'; source=$privatePath; target='/var/lib/servicios-tecnicos'}
$mountJson = ConvertTo-Json -InputObject $mounts -Depth 12 -Compress
$override = @"
# Generated by Pruebas/.docker/start.ps1 from the CURRENT base Compose file.
services:
  app:
    entrypoint: ["docker-php-entrypoint"]
    command: ["apache2-foreground"]
    environment:
      TECH_STORAGE_DIR: /var/lib/servicios-tecnicos
    volumes: !override $mountJson
"@
[IO.File]::WriteAllText($overrideCompose, $override, (New-Object System.Text.UTF8Encoding($false)))
& docker compose -f $baseCompose -f $overrideCompose config --quiet
if ($LASTEXITCODE -ne 0) { throw 'La configuración de Servicios Técnicos no es válida.' }
if ($PrepareOnly) { Write-Output 'Configuración preparada y validada.'; return }
& docker compose -f $baseCompose -f $overrideCompose up -d --no-deps --no-build app
if ($LASTEXITCODE -ne 0) { throw 'No se pudo iniciar Servicios Técnicos.' }
Write-Output 'Servicios Técnicos: http://127.0.0.1:8085/Pruebas/index.php'
